const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { credentialValues, securityAudit } = require('./vsix-accept.cjs')

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'coding-agent-vsix-security-'))
try {
  const token = `fixture-secret-${process.pid}-not-a-real-credential`
  const values = credentialValues({ records: [{ accessToken: token }, { nested: { api_key: 'another-fixture-secret' } }] })
  assert.deepEqual(values, [token, 'another-fixture-secret'])
  assert.deepEqual(credentialValues({ token: 'short', ordinary: token }), [], '短值或非敏感字段不得被误当作凭据')
  assert.deepEqual(credentialValues({ ordinary: { token } }), [token], '嵌套敏感字段仍须保守扫描')
  const credential = path.join(root, 'credentials.yaml')
  fs.writeFileSync(credential, `accessToken: ${token}\n`, { mode: 0o600 })
  const logs = path.join(root, 'logs')
  fs.mkdirSync(logs)
  const log = path.join(logs, 'agent.log')
  fs.writeFileSync(log, 'No credentials in this fixture.\n')
  const archive = path.join(root, 'fixture.vsix')
  fs.writeFileSync(archive, 'Fixture archive')
  const clean = securityAudit(root, [logs], credential, archive, path.basename(archive))
  assert.equal(clean.scannedFileCount, 1)
  assert.equal(clean.credentialValueCount, 1)
  assert.ok(!JSON.stringify(clean).includes(token))
  fs.writeFileSync(log, token)
  assert.throws(() => securityAudit(root, [logs], credential, archive, path.basename(archive)), /授权材料/)
  fs.writeFileSync(log, 'No credentials in this fixture.\n')
  fs.writeFileSync(archive, token)
  assert.throws(() => securityAudit(root, [], credential, archive, path.basename(archive)), /授权材料/, '归档本身必须扫描')
  fs.writeFileSync(archive, 'Fixture archive')
  fs.writeFileSync(credential, 'version: 1\nrecords: {}\n')
  assert.throws(() => securityAudit(root, [logs], credential, archive, path.basename(archive)), /未找到可验证的授权值/)
  console.log('VSIX credential scanner, archive/log leakage and empty-credential rejection passed')
} finally { fs.rmSync(root, { recursive: true, force: true }) }
