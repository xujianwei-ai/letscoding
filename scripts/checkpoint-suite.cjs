const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const Module = require('node:module')

async function loadCheckpointStore() {
  if (process.env.VSCODE_AGENT_SUITE === 'checkpoint-suite.cjs') {
    const vscode = require('vscode')
    return { ...require('../out/checkpoints.js'), workspace: vscode.workspace.workspaceFolders[0].uri.fsPath }
  }
  const hook = Module.registerHooks({ resolve: (specifier, context, next) => specifier === 'vscode'
    ? { url: 'data:text/javascript,export const workspace = {}', shortCircuit: true } : next(specifier, context) })
  try {
    const { CheckpointStore, workspacePath } = await import('../out/checkpoints.js')
    return { CheckpointStore, workspacePath, workspace: require('node:os').tmpdir() }
  } finally { hook.deregister() }
}

async function run() {
  const { CheckpointStore, workspacePath, workspace } = await loadCheckpointStore()
  const root = fs.mkdtempSync(path.join(workspace, 'checkpoint-unit-workspace-'))
  const store = new CheckpointStore(path.join(root, 'storage'))
  const started = await store.before('checkpoint-session', root, 7, 'change the fixture')
  const file = path.join(root, 'file.txt')
  const created = path.join(root, 'created.txt')
  const second = path.join(root, 'second.txt')
  const deleted = path.join(root, 'deleted.txt')
  fs.writeFileSync(file, 'ORIGINAL\n')
  fs.writeFileSync(second, 'SECOND ORIGINAL\n')
  fs.writeFileSync(deleted, 'DELETED ORIGINAL\n')
  await store.track('checkpoint-session', root, file)
  fs.writeFileSync(file, 'FIRST\n')
  await store.track('checkpoint-session', root, file)
  fs.writeFileSync(file, 'SECOND\n')
  await store.track('checkpoint-session', root, second)
  await store.track('checkpoint-session', root, deleted)
  fs.writeFileSync(second, 'SECOND CHANGE\n')
  fs.rmSync(deleted)
  await assert.rejects(store.track('checkpoint-session', root, path.join(root, '.env')), /敏感文件/)
  await store.track('checkpoint-session', root, created)
  fs.writeFileSync(created, 'CREATED\n')
  await store.track('checkpoint-session', root, created)
  fs.writeFileSync(created, 'MODIFIED AFTER FIRST CAPTURE\n')
  const checkpoint = (await store.list('checkpoint-session')).find(item => item.id === started.id)
  assert.deepEqual(checkpoint.files, ['file.txt', 'second.txt', 'deleted.txt', 'created.txt'])
  const storage = path.join(root, 'storage')
  const firstSnapshot = JSON.parse(fs.readFileSync(path.join(storage, `${checkpoint.id}-ZmlsZS50eHQ.json`), 'utf8'))
  const createdSnapshot = JSON.parse(fs.readFileSync(path.join(storage, `${checkpoint.id}-Y3JlYXRlZC50eHQ.json`), 'utf8'))
  const blob = JSON.parse(fs.readFileSync(path.join(storage, 'blobs', `${firstSnapshot[0].hash}.json`), 'utf8'))
  assert.equal(Buffer.from(blob.content, 'base64').toString(), 'ORIGINAL\n')
  assert.equal(createdSnapshot[0].content, undefined)
  fs.writeFileSync(file, 'LATER USER EDIT\n')
  const legacyPlan = await store.previewRestore(root, 'checkpoint-session', 7)
  assert.equal(legacyPlan.changes.find(change => change.path === 'file.txt').conflict, true, 'Legacy snapshots conservatively protect later edits')
  await store.backupForUndo('child', root, checkpoint.files)
  await store.restore(root, checkpoint.id)
  assert.equal(fs.readFileSync(file, 'utf8'), 'ORIGINAL\n')
  assert.equal(fs.readFileSync(second, 'utf8'), 'SECOND ORIGINAL\n')
  assert.equal(fs.readFileSync(deleted, 'utf8'), 'DELETED ORIGINAL\n')
  assert.equal(fs.existsSync(created), false)
  await store.undo(root, 'child')
  assert.equal(fs.readFileSync(file, 'utf8'), 'LATER USER EDIT\n')
  assert.equal(workspacePath(root, file), 'file.txt')
  assert.throws(() => workspacePath(root, '../escape.txt'))
  assert.throws(() => workspacePath(root, '.git/config'))
  await store.after('checkpoint-session', 1)
  const reloaded = new CheckpointStore(path.join(root, 'storage'))
  assert.equal((await reloaded.list('checkpoint-session'))[0].turn, 1)
  await reloaded.rebindSession('checkpoint-session', 'forked-session', 8)
  const inherited = (await reloaded.list('forked-session'))[0]
  assert.equal(inherited.id, checkpoint.id)
  assert.equal((await reloaded.list('checkpoint-session')).length, 1)
  const baselineWorkspace = path.join(root, 'baseline-workspace')
  const pythonFile = path.join(baselineWorkspace, 'test_string_utils.py')
  fs.mkdirSync(baselineWorkspace, { recursive: true })
  fs.writeFileSync(pythonFile, 'class TestTextHelpers:\n    pass\n')
  const baselineStore = new CheckpointStore(path.join(root, 'baseline-storage'))
  await baselineStore.before('baseline-session', baselineWorkspace, 3, 'rename test class')
  await baselineStore.track('baseline-session', baselineWorkspace, pythonFile)
  fs.writeFileSync(pythonFile, 'class TestStringBehaviors:\n    pass\n')
  const expectedBaseline = 'class TestTextHelpers:\n    pass\n'
  assert.equal((await baselineStore.baseline('baseline-session', 3, 'test_string_utils.py', baselineWorkspace)).toString(), expectedBaseline)
  assert.equal((await baselineStore.baseline('baseline-session', 3, pythonFile, baselineWorkspace)).toString(), expectedBaseline, 'Editor and Diff button must accept absolute workspace paths')
  await assert.rejects(baselineStore.baseline('baseline-session', 3, path.join(root, 'outside.py'), baselineWorkspace), /超出工作区/)
  console.log('Checkpoint baseline accepts absolute and relative Python file paths')
  fs.writeFileSync(file, 'FORK BRANCH MODIFIED\n')
  await store.restore(root, inherited.id)
  assert.equal(fs.readFileSync(file, 'utf8'), 'ORIGINAL\n')
  const full = new CheckpointStore(path.join(root, 'full-storage'))
  fs.writeFileSync(file, 'BEFORE FIRST\n')
  fs.writeFileSync(second, 'KEEP\n')
  const initial = await full.before('full-session', root, 1, 'first')
  await full.track('full-session', root, file)
  await full.track('full-session', root, created)
  fs.writeFileSync(file, 'FIRST\n')
  fs.writeFileSync(created, 'CREATED BY BASH\n')
  await full.after('full-session', 1)
  await full.before('full-session', root, 2, 'second')
  await full.track('full-session', root, file)
  await full.track('full-session', root, second)
  fs.writeFileSync(file, 'SECOND\n')
  fs.writeFileSync(second, 'CHANGED LATER\n')
  await full.finish('full-session', root)
  await full.after('full-session', 2)
  const cleanPlan = await full.previewRestore(root, 'full-session', 1)
  assert.equal(cleanPlan.changes.find(change => change.path === 'file.txt').conflict, false, 'Normal Agent edits must not be reported as manual conflicts')
  assert.equal(cleanPlan.changes.find(change => change.path === 'file.txt').target.toString(), 'BEFORE FIRST\n')
  assert.equal(cleanPlan.changes.find(change => change.path === 'created.txt').kind, 'delete')
  assert.equal(cleanPlan.changes.find(change => change.path === 'created.txt').current.toString(), 'CREATED BY BASH\n')
  fs.writeFileSync(file, 'MANUAL CONFLICT\n')
  fs.writeFileSync(created, 'MANUAL NEW FILE EDIT\n')
  const conflictPlan = await full.previewRestore(root, 'full-session', 1)
  assert.equal(conflictPlan.changes.find(change => change.path === 'file.txt').conflict, true)
  console.log('Conflict classification passed')
  assert.equal(conflictPlan.changes.find(change => change.path === 'second.txt').conflict, false)
  assert.equal(conflictPlan.changes.find(change => change.path === 'created.txt').conflict, true, 'Manually edited Agent-created files require an explicit choice')
  assert.equal(conflictPlan.changes.find(change => change.path === 'file.txt').current.toString(), 'MANUAL CONFLICT\n')
  const hashes = new Map(conflictPlan.changes.map(change => [change.path, change.currentHash]))
  const manual = path.join(root, 'manual-untouched.txt')
  fs.writeFileSync(manual, 'MANUAL\n')
  const unchanged = path.join(root, 'unchanged.txt')
  fs.writeFileSync(unchanged, 'UNCHANGED\n')
  const unchangedStat = fs.statSync(unchanged)
  assert.equal((await full.previewRestore(root, 'full-session', 1)).changes.some(change => change.path === 'manual-untouched.txt'), false, 'A later manual file must not appear as a delete conflict')
  fs.writeFileSync(file, 'EDIT AFTER PREVIEW\n')
  await assert.rejects(full.restoreFrom(root, 'full-session', 1, hashes), /预览后发生变化/)
  assert.equal(fs.readFileSync(file, 'utf8'), 'EDIT AFTER PREVIEW\n', 'A stale preview must never overwrite new edits')
  fs.writeFileSync(file, 'MANUAL CONFLICT\n')
  await full.backupForUndo('full-child', root, [file, second, created])
  await full.restoreFrom(root, 'full-session', 1, hashes)
  assert.equal(fs.readFileSync(file, 'utf8'), 'BEFORE FIRST\n', 'Full rollback must undo both later turns')
  assert.equal(fs.statSync(unchanged).mtimeMs, unchangedStat.mtimeMs, 'Untouched files must not be rewritten during rollback')
  await full.restoreFrom(root, 'full-session', 1)
  assert.equal(fs.readFileSync(manual, 'utf8'), 'MANUAL\n', 'An untouched manual file must survive full rollback')
  assert.equal(fs.readFileSync(second, 'utf8'), 'KEEP\n')
  assert.equal(fs.existsSync(created), false, 'Full rollback must remove later untracked files')
  assert.ok(fs.existsSync(path.join(root, 'full-storage', `${initial.id}.json`)), 'Private snapshot data must not be deleted')
  await full.undo(root, 'full-child')
  assert.equal(fs.readFileSync(file, 'utf8'), 'MANUAL CONFLICT\n', 'Undo preserves the manual state captured immediately before restore')
  assert.equal(fs.readFileSync(created, 'utf8'), 'MANUAL NEW FILE EDIT\n', 'Undo restores the manually edited new file captured before restore')
  await assert.rejects(full.restoreFrom(root, 'full-session', 999), /没有代码检查点/)
  console.log('Full workspace multi-turn rollback, Bash-created files, undo and incomplete snapshot rejection passed')
  console.log('Checkpoint multi-file restore, deleted/new file, undo, fork inheritance, path boundary and persistence passed')
}
module.exports = { run }
