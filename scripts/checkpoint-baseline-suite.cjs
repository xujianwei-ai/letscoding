const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')

async function run() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'coding-agent-baseline-'))
  try {
    const vscode = 'data:text/javascript;base64,' + Buffer.from('export const window = {}').toString('base64')
    const source = fs.readFileSync(require.resolve('../out/checkpoints.js'), 'utf8')
      .replace("from 'vscode'", `from ${JSON.stringify(vscode)}`)
    const { CheckpointStore } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'))
    const workspace = path.join(root, 'workspace')
    const file = path.join(workspace, 'test_string_utils.py')
    fs.mkdirSync(workspace, { recursive: true })
    fs.writeFileSync(file, 'class TestTextHelpers:\n    pass\n')
    const store = new CheckpointStore(path.join(root, 'storage'))
    await store.before('baseline-session', workspace, 3, 'rename test class')
    await store.track('baseline-session', workspace, file)
    fs.writeFileSync(file, 'class TestStringBehaviors:\n    pass\n')
    const expected = 'class TestTextHelpers:\n    pass\n'
    assert.equal((await store.baseline('baseline-session', 3, 'test_string_utils.py', workspace)).toString(), expected)
    assert.equal((await store.baseline('baseline-session', 3, file, workspace)).toString(), expected, 'Absolute editor paths must resolve against the workspace')
    await assert.rejects(store.baseline('baseline-session', 3, path.join(root, 'outside.py'), workspace), /超出工作区/)
    await store.after('baseline-session', 1)
    await store.rebindSession('baseline-session', 'forked-session', 4)
    await store.deleteSession('baseline-session')
    assert.equal((await store.baseline('forked-session', 3, file, workspace)).toString(), expected, 'Deleting a source must retain shared fork snapshots')
    assert.equal(await store.baseline('baseline-session', 3, file, workspace), undefined)
    await store.deleteSession('forked-session')
    assert.equal(await store.baseline('forked-session', 3, file, workspace), undefined)
    assert.equal(fs.existsSync(path.join(root, 'storage/blobs')), true)
    assert.deepEqual(fs.readdirSync(path.join(root, 'storage/blobs')), [], 'Last deletion removes unreferenced blobs')
    console.log('Checkpoint baseline accepts absolute and relative Python file paths')
    const large = path.join(workspace, 'closure-v8.log')
    const fd = fs.openSync(large, 'w')
    fs.ftruncateSync(fd, 10 * 1024 * 1024 + 1)
    fs.closeSync(fd)
    const largeStore = new CheckpointStore(path.join(root, 'large-storage'))
    await largeStore.before('large-session', workspace, 1, 'ignore a pre-existing log')
    fs.writeFileSync(file, 'SMALL CHANGE\n')
    await largeStore.track('large-session', workspace, file)
    const saved = (await largeStore.list('large-session'))[0]
    assert.equal(saved.workspaceFiles.includes('closure-v8.log'), false)
    assert.equal(saved.untrackedLargeFiles['closure-v8.log'].size, 10 * 1024 * 1024 + 1)
    await largeStore.trackWorkspaceChanges('large-session', workspace)
    await largeStore.finish('large-session', workspace)
    await largeStore.after('large-session', 1)
    await largeStore.restoreFrom(workspace, 'large-session', 1)
    assert.equal(fs.readFileSync(file, 'utf8'), 'class TestStringBehaviors:\n    pass\n')
    assert.ok(fs.existsSync(large), 'An unchanged pre-existing large file must not be deleted by rollback')
    await largeStore.before('large-session', workspace, 2, 'detect a modified large log')
    fs.appendFileSync(large, 'new data')
    await assert.rejects(largeStore.track('large-session', workspace, large), /10 MiB.*不会自动恢复/)
    fs.writeFileSync(file, 'LATER SMALL CHANGE\n')
    await largeStore.track('large-session', workspace, file)
    await assert.rejects(largeStore.trackWorkspaceChanges('large-session', workspace), /大文件.*手动审查/)
    const newLarge = path.join(workspace, 'downloads', 'node-v24.9.0-linux-x64.tar.xz')
    fs.mkdirSync(path.dirname(newLarge), { recursive: true })
    const createdFd = fs.openSync(newLarge, 'w')
    fs.ftruncateSync(createdFd, 10 * 1024 * 1024 + 1)
    fs.closeSync(createdFd)
    await assert.rejects(largeStore.trackWorkspaceChanges('large-session', workspace), /node-v24/)
    await largeStore.finish('large-session', workspace)
    await largeStore.after('large-session', 2)
    const preview = await largeStore.previewRestore(workspace, 'large-session', 2)
    const largePreview = preview.changes.find(change => change.path === 'closure-v8.log')
    assert.equal(largePreview.conflict, true)
    assert.equal(largePreview.current, undefined, 'Restore preview must never buffer a large file')
    const hashes = new Map(preview.changes.map(change => [change.path, change.currentHash]))
    await largeStore.restoreFrom(workspace, 'large-session', 2, hashes, preview)
    assert.equal(fs.readFileSync(file, 'utf8'), 'class TestStringBehaviors:\n    pass\n')
    assert.ok(fs.statSync(large).size > 10 * 1024 * 1024, 'Changed large files remain untouched during rollback')
    await largeStore.backupForUndo('large-session', workspace, preview.changes.map(change => change.path))
    await largeStore.undo(workspace, 'large-session')
    assert.ok(fs.statSync(large).size > 10 * 1024 * 1024, 'Undo must never delete an untracked large file')
    const newLargePreview = await largeStore.previewRestore(workspace, 'large-session', 2)
    assert.equal(newLargePreview.changes.find(change => change.path.includes('node-v24')).current, undefined)
    await largeStore.restoreFrom(workspace, 'large-session', 2, new Map(newLargePreview.changes.map(change => [change.path, change.currentHash])), newLargePreview)
    assert.ok(fs.existsSync(newLarge), 'New large downloads must not be treated as small created files')
    console.log('Large files avoid buffering, turn interruption, accidental rollback and undo deletion')
  } finally {
    fs.rmSync(root, { recursive: true, force: true })
  }
}

async function verifyRegression() {
  const { testSummary } = await import('../out/diagnostics.js')
  const { VerificationTracker } = await import('../out/verification.js')
  const direct = 'FAIL: test_reverse_word (__main__.TestStringBehaviors.test_reverse_word)\nTraceback (most recent call last):\n  File "/tmp/workspace/test_string_utils.py", line 6, in test_reverse_word\nAssertionError: bad'
  const imported = 'FAIL: test_reverse_word (test_string_utils.TestStringBehaviors.test_reverse_word)\nTraceback (most recent call last):\n  File "/tmp/workspace/test_string_utils.py", line 6, in test_reverse_word\nAssertionError: bad'
  const directSummary = testSummary('python test_string_utils.py', `EXIT_CODE=1\n${direct}`)
  assert.equal(directSummary.status, 'failed')
  assert.equal(directSummary.exitCode, 1)
  assert.match(directSummary.rerunCommand, /test_string_utils\.TestStringBehaviors\.test_reverse_word/)
  assert.equal(testSummary('python test_string_utils.py', '[stderr]\nFAIL: broken\nTraceback (most recent call last):\nFAILED (failures=1)', false).failures.length, 1)
  const tracker = new VerificationTracker('/tmp/workspace')
  tracker.record('/tmp/workspace', 'python test_string_utils.py', direct, true)
  assert.ok(tracker.rerunCommand())
  assert.ok(tracker.rerunCommand(), 'Publishing a report must not invalidate its own rerun command')
  const targeted = tracker.rerunCommand()
  tracker.record('/tmp/workspace', targeted, imported, true)
  assert.equal(tracker.report([]).failures.filter(item => !item.resolved).length, 1)
  assert.equal(tracker.report([]).runs.at(-1).exitCode, undefined)
  tracker.record('/tmp/workspace', targeted, 'OK\n[exit code: 0]', false)
  assert.equal(tracker.report([]).status, 'failed', 'An OK word alone must not clear a failed test')
  assert.equal(tracker.rerunCommand(), undefined, 'Unknown evidence must not offer a passing rerun action')
  tracker.record('/tmp/workspace', targeted, 'Ran 1 test in 0.001s\n\nOK\n[exit code: 0]', false)
  assert.equal(tracker.report([]).status, 'passed')
  const scoped = new VerificationTracker('/tmp/workspace')
  scoped.record('/tmp/workspace', 'node --test a.test.js', 'not ok 1 - alpha\n# pass 0\n# fail 1\n# tests 1', true)
  scoped.record('/tmp/workspace', 'node --test b.test.js', '# pass 1\n# fail 0\n# tests 1\n[exit code: 0]', false)
  assert.equal(scoped.report([]).status, 'failed', 'A passing unrelated test must not resolve an earlier failure')
  scoped.record('/tmp/workspace', 'node --test a.test.js', '# pass 1\n# fail 0\n# tests 1\n[exit code: 0]', false)
  assert.equal(scoped.report([]).status, 'passed')
  console.log('Verification regression checks passed')
}

run().then(verifyRegression).catch(error => { console.error(error); process.exitCode = 1 })
