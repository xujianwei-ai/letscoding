const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const { baselinePath, validateLock } = require('./runtime-baseline.cjs')
const { createClosure, collectClosure, inspectNative, isCompatible, assertNoHostPaths, main, generatedPath, stagedInventory } = require('./runtime-closure.cjs')

const repository = path.resolve(__dirname, './dsh-learning/deepseek-harness')
const lock = JSON.parse(fs.readFileSync(baselinePath, 'utf8'))
const baseline = JSON.parse(fs.readFileSync(path.resolve(__dirname, '../build/runtime-baseline.json'), 'utf8'))
assert.ok(validateLock(lock).dsh.productionClosure.roots.includes('@deepseek-ai/dsh-sdk-app'))
assert.throws(() => main(['--copy-all']), /未知参数/)
assert.equal(isCompatible({ os: ['linux'], cpu: ['x64'] }, lock.platform), true)
assert.equal(isCompatible({ os: ['darwin'] }, lock.platform), false)
assert.equal(isCompatible({ os: ['!darwin'] }, lock.platform), true)
assert.equal(isCompatible({ os: ['!linux', '!win32'] }, lock.platform), false)

const closure = createClosure(lock, repository, { sourceBaseline: baseline })
assert.equal(closure.packageCount, 227)
assert.equal(closure.externalPackageCount, 45)
assert.equal(closure.dsh.source.treeSha256, baseline.dsh.snapshot.treeSha256)
assert.deepEqual(closure.missing, [], '已构建且可发布闭包不得有缺失')
assert.ok(closure.packages.some(item => item.name === '@deepseek-ai/dsh-sdk-jsonrpc-server'))
assert.ok(closure.packages.some(item => item.name === '@deepseek-ai/dsh-base'))
assert.ok(closure.packages.some(item => item.name === '@deepseek-ai/cordis'))
assert.ok(closure.packages.every(item => !path.isAbsolute(item.source)))
assert.ok(!closure.packages.some(item => item.name === '@deepseek-ai/node-addon-system-darwin-arm64'))
assert.ok(closure.packages.some(item => item.name === 'commander'))
assert.equal(closure.status, 'pending-build-or-missing-inputs')
assert.ok(fs.existsSync(generatedPath))
assert.doesNotThrow(() => main(['--check'], { repository, sourceBaseline: baseline }))
assert.throws(() => main(['--check'], { repository, sourceBaseline: baseline, staging: path.join(os.tmpdir(), 'missing-runtime-staging') }), /发布暂存区不存在/)
const previewDirectory = fs.mkdtempSync(path.join(os.tmpdir(), 'runtime-package-preview-'))
try {
  const previewPath = path.join(previewDirectory, 'preview.json')
  const preview = main(['--package-preview'], { repository, sourceBaseline: baseline, generatedPath: previewPath })
  assert.equal(preview.status, 'pending-build-or-missing-inputs')
  assert.equal(preview.artifacts.fileCount, 0)
  assert.doesNotThrow(() => main(['--package-preview', '--check'], { repository, sourceBaseline: baseline, generatedPath: previewPath }))
} finally { fs.rmSync(previewDirectory, { recursive: true, force: true }) }
const original = fs.readFileSync(generatedPath, 'utf8')
assert.throws(() => main(['--check'], { repository, sourceBaseline: { ...baseline, dsh: { ...baseline.dsh, snapshot: { ...baseline.dsh.snapshot, treeSha256: '0'.repeat(64) } } } }), /源码树与 A2 基线不一致/)
assert.equal(fs.readFileSync(generatedPath, 'utf8'), original, '失败检查不得改写已审查清单')
const withoutLock = { ...baseline, dsh: { ...baseline.dsh, snapshot: { ...baseline.dsh.snapshot, files: baseline.dsh.snapshot.files.filter(item => item.path !== 'pnpm-lock.yaml') } } }
assert.throws(() => createClosure(lock, repository, { sourceBaseline: withoutLock }), /lockfile 与 A2 基线不一致/)
assert.throws(() => assertNoHostPaths({ packages: [{ name: 'bad', source: process.cwd() }], files: [] }, repository), /开发机路径/)
assert.throws(() => assertNoHostPaths({ packages: [{ name: 'bad', source: 'ok' }], files: [{ package: 'bad', path: '/tmp/outside.js' }] }, repository), /绝对路径/)
const graph = collectClosure(lock, repository)
assert.ok(graph.linkFindings.every(item => !/^(?:lib|bin|dist)\//.test(item.path)), '生产构建目录的链接不得通过审核')

// Exercise missing native files without altering the real workspace.
const nativeCopy = fs.mkdtempSync(path.join(os.tmpdir(), 'runtime-closure-native-'))
try {
  const source = path.join(repository, 'native/system/packages/entry/node_modules/@deepseek-ai/node-addon-system-linux-x64')
  const destination = path.join(nativeCopy, 'native/system/packages/entry/node_modules/@deepseek-ai/node-addon-system-linux-x64')
  fs.cpSync(source, destination, { recursive: true, dereference: true })
  const checked = inspectNative(nativeCopy, lock.platform)
  assert.equal(checked.failures.length, 0)
  fs.rmSync(path.join(destination, 'bin/glibc/system.node'))
  assert.equal(inspectNative(nativeCopy, lock.platform).failures.length, 1)
  fs.writeFileSync(path.join(destination, 'bin/landlock-run'), 'test')
  fs.chmodSync(path.join(destination, 'bin/landlock-run'), 0o644)
  assert.ok(inspectNative(nativeCopy, lock.platform).failures.some(item => item.path === 'bin/landlock-run'), '启动器不可执行必须被拒绝')
  fs.unlinkSync(path.join(destination, 'bin/landlock-run'))
  fs.symlinkSync('/etc/passwd', path.join(destination, 'bin/landlock-run'))
  assert.throws(() => inspectNative(nativeCopy, lock.platform), /不接受链接/)
} finally {
  fs.rmSync(nativeCopy, { recursive: true, force: true })
}
const rootStaging = path.resolve(__dirname, '../.runtime-build/dsh')
const stagedCopy = fs.mkdtempSync(path.join(os.tmpdir(), 'runtime-staged-inventory-'))
try {
  const target = path.join(stagedCopy, 'node_modules/@deepseek-ai/dsh-sdk-client/lib')
  fs.mkdirSync(target, { recursive: true })
  for (const item of graph.records.values()) {
    const directory = path.join(stagedCopy, item.stagingPath ?? path.join('node_modules', ...item.name.split('/')))
    fs.mkdirSync(directory, { recursive: true })
    const manifest = fs.readFileSync(path.join(rootStaging, 'node_modules', ...item.name.split('/'), 'package.json'), 'utf8')
    fs.writeFileSync(path.join(directory, 'package.json'), manifest)
  }
  const nativeSource = path.join(repository, closure.native.directory)
  const nativeTarget = path.join(stagedCopy, 'node_modules', ...closure.native.package.split('/'))
  for (const binary of closure.native.payloads) {
    const destination = path.join(nativeTarget, binary.path)
    fs.mkdirSync(path.dirname(destination), { recursive: true })
    fs.copyFileSync(path.join(nativeSource, binary.path), destination)
    fs.chmodSync(destination, 0o755)
  }
  fs.writeFileSync(path.join(target, 'index.js'), 'export {}\n')
  fs.writeFileSync(path.join(stagedCopy, 'stray.js'), 'export {}\n')
  assert.throws(() => stagedInventory(repository, graph, stagedCopy, closure.native), /文件不属于登记的包/)
  fs.rmSync(path.join(stagedCopy, 'stray.js'))
  fs.symlinkSync('/etc/passwd', path.join(target, 'escape.js'))
  assert.throws(() => stagedInventory(repository, graph, stagedCopy, closure.native), /包含符号链接/)
  fs.rmSync(path.join(target, 'escape.js'))
  assert.doesNotThrow(() => stagedInventory(repository, graph, stagedCopy, closure.native))
  fs.rmSync(path.join(stagedCopy, 'node_modules/@deepseek-ai/dsh/package.json'))
  assert.throws(() => stagedInventory(repository, graph, stagedCopy, closure.native), /dsh\/package\.json/)
  const report = JSON.parse(fs.readFileSync(generatedPath, 'utf8'))
  assert.equal(report.artifacts.fileCount, report.artifacts.files.length)
  assert.equal(report.artifacts.packageFileCount, report.artifacts.packages.reduce((sum, item) => sum + item.fileCount, 0))
  assert.equal(report.artifacts.unpackedBytes, report.artifacts.packages.reduce((sum, item) => sum + item.unpackedBytes, 0))
  assert.equal(report.artifacts.unpackedBytes, report.artifacts.files.filter(item => item.package).reduce((sum, item) => sum + item.bytes, 0))
  assert.equal(report.artifacts.files.reduce((sum, item) => sum + item.bytes, 0), report.artifacts.unpackedBytes + report.artifacts.files.filter(item => !item.package).reduce((sum, item) => sum + item.bytes, 0))
  assert.equal(report.status, 'artifact-inventory-complete')
} finally {
  fs.rmSync(stagedCopy, { recursive: true, force: true })
}
console.log(`Runtime closure: ${closure.packageCount} package nodes, ${closure.externalPackageCount} external resolutions, staged file audit, path/source drift and native gap rejection passed`)
